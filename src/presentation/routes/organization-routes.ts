import type { FastifyInstance } from 'fastify';
import type { ApplicationServices } from '../services.js';
import { EmployeeController } from '../controllers/employee-controller.js';
import { OrganizationController } from '../controllers/organization-controller.js';
import { AttendanceController } from '../controllers/attendance-controller.js';
import { AttendanceFileController } from '../controllers/attendance-file-controller.js';
import { idParams } from '../validators/common.js';
import { z } from 'zod';

export function registerOrganizationRoutes(app: FastifyInstance, services: ApplicationServices): void {
  const employees = new EmployeeController(services);
  const organization = new OrganizationController(services);
  const attendance = new AttendanceController(services);
  const files = new AttendanceFileController(services.attendanceFile);
  app.post('/attendance/imports/preview', { bodyLimit: 2_000_000 }, files.preview);
  app.post('/attendance/imports', { bodyLimit: 2_000_000 }, files.import);
  app.get('/attendance/imports', files.history);
  app.get('/employees/:id', employees.find);
  app.post('/employees', employees.create);
  app.post('/employees/:id/identify', employees.identify);
  app.post('/employees/:id/discard',async (request,reply) => {
    const input = z.object({reason:z.string().trim().min(1).max(500).default('Registro pendiente sin checadas.')}).strict().parse(request.body ?? {});
    await services.discardEmployee.execute(idParams.parse(request.params).id,services.access.current()!,input.reason);
    return reply.code(204).send();
  });
  app.post('/employees/:id/clock-record', employees.assignClock);
  app.get('/employees/:id/history', employees.history);
  app.get('/employees/:id/attendance', employees.attendance);
  app.patch('/employees/:id', employees.update);
  app.get('/employees/:id/scheduling', employees.scheduling);
  app.put('/employees/:id/scheduling', employees.saveScheduling);
  app.patch('/users/:id/profile', employees.updateProfile);
  app.get('/branches', organization.branches);
  app.post('/branches', organization.createBranch);
  app.put('/branches/:id', organization.updateBranch);
  app.get('/branch-policies', organization.policies);
  app.get('/branch-configurations', organization.configurations);
  app.get('/branches/:id/configuration', organization.configuration);
  app.post('/branches/:id/configuration', organization.saveConfiguration);
  app.delete('/branches/:id/configuration/versions/:versionId', organization.deleteConfiguration);
  app.post('/branches/:id/policies', organization.createPolicy);
  app.get('/work-schedules', organization.schedules);
  app.post('/work-schedules', organization.createSchedule);
  app.get('/schedule-assignments', organization.assignments);
  app.post('/organization/assignments', organization.assign);
  app.post('/work-schedules/:id/assignments', organization.assignSchedule);
  app.post('/branches/:id/assignments', organization.assignBranch);
  app.get('/attendance/daily', attendance.daily);
  app.get('/attendance/cards', attendance.cards);
  app.get('/attendance/cards/export', attendance.exportCards);
  app.get('/attendance/overtime', attendance.overtime);
  app.get('/attendance/overtime/export', attendance.exportOvertime);
  app.get('/attendance/deductions', attendance.deductions);
  app.post('/attendance/recalculate', attendance.recalculate);
}
